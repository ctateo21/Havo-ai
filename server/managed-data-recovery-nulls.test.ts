type Row = Record<string, unknown>;

function targetClient(data: Record<string, Row[]>) {
  return {
    async readPage(table: string, _primaryKey: string[], from: number, to: number) {
      return { rows: data[table].slice(from, to + 1), count: data[table].length };
    },
  };
}

function nullFixture(): Record<string, Row[]> {
  const fixture = Object.fromEntries(TABLES.map(([, target, key]) => {
    const row = Object.fromEntries(key.split(",").map((column, index) => [
      column,
      column === "address_normalized" ? "address" :
        column === "policy_type" ? "HO3" :
          column === "dedupe_key" ? "claim" : index + 1,
    ]));
    return [target, [row]];
  })) as Record<string, Row[]>;
  fixture.managed_integration_requests = [
    {
      id: 1, submission_id: 10, provider: "test", request_data: "null",
      response_data: null, status: "pending", created_at: "2026-01-01T00:00:00.000Z",
    },
    {
      id: 2, submission_id: 10, provider: "test", request_data: "null",
      response_data: "null", status: "pending", created_at: "2026-01-01T00:00:00.000Z",
    },
  ];
  return fixture;
}

test("recovery JSON normalization reserves JavaScript null for SQL NULL", () => {
  assert.deepEqual(recoveryJsonColumns("managed_integration_requests"), [
    "request_data", "response_data",
  ]);
  const rows = normalizeRecoveryRows("managed_integration_requests", [
    { request_data: " { \"number\": 9007199254740993 } ", response_data: null },
    { request_data: "null", response_data: "null" },
  ]);
  assert.deepEqual(rows, [
    { request_data: '{"number":9007199254740993e0}', response_data: null },
    { request_data: "null", response_data: "null" },
  ]);
  assert.notEqual(
    recoveryChecksum(rows[0].response_data),
    recoveryChecksum(rows[1].response_data),
  );
});

test("production target reader requires and consumes JSON text aliases", async () => {
  let selected = "";
  const request = async (input: URL | RequestInfo) => {
    const url = new URL(String(input));
    selected = url.searchParams.get("select") ?? "";
    return new Response(JSON.stringify([{
      id: 1,
      request_data: { rounded_by_rest: true },
      response_data: { rounded_by_rest: true },
      [recoveryJsonAlias("request_data")]: "null",
      [recoveryJsonAlias("response_data")]: null,
    }]), {
      status: 200,
      headers: { "content-range": "0-0/1" },
    });
  };
  const reader = createRecoveryTargetReader("https://example.test", "secret", request as typeof fetch);
  const page = await reader.readPage("managed_integration_requests", ["id"], 0, 0);
  assert.match(selected, /__recovery_json_request_data:request_data::text/);
  assert.deepEqual(page.rows, [{ id: 1, request_data: "null", response_data: null }]);

  const missingAlias = createRecoveryTargetReader(
    "https://example.test",
    "secret",
    (async () => new Response('[{"id":1}]', {
      status: 200, headers: { "content-range": "0-0/1" },
    })) as typeof fetch,
  );
  await assert.rejects(
    missingAlias.readPage("managed_integration_requests", ["id"], 0, 0),
    /Recovery target read failed/,
  );
});

const liveDatabase = process.env.NODE_ENV === "production" ? undefined : process.env.DATABASE_URL;
for (const jsonType of ["json", "jsonb"]) {
test(`isolated ${jsonType} restore keeps SQL NULL distinct from JSON null`, { skip: !liveDatabase }, async () => {
  const pool = createMigrationSourcePool(liveDatabase!);
  const source = await pool.connect();
  const inspector = await pool.connect();
  const schema = `recovery_nulls_${randomUUID().replaceAll("-", "_")}`;
  const quote = (name: string) => `"${name.replaceAll('"', '""')}"`;
  const data = nullFixture();
  try {
    await source.query(`create schema ${quote(schema)}`);
    for (const [name, target, primaryKey] of TABLES) {
      if (name === "integration_requests") {
        await source.query(`create table ${quote(schema)}.${quote(name)} (
          id integer generated by default as identity primary key,
          submission_id integer not null, provider text not null,
          request_data ${jsonType} not null, response_data ${jsonType === "json" ? "jsonb" : "json"},
          status text, created_at timestamp without time zone
        )`);
        continue;
      }
      const columns = primaryKey.split(",").map(column =>
        `${quote(column)} ${column === "address_normalized" || column === "policy_type" ||
          column === "dedupe_key" ? "text" : "integer"}`);
      await source.query(`create table ${quote(schema)}.${quote(name)}
        (${columns.join(", ")}, primary key (${primaryKey.split(",").map(quote).join(", ")}))`);
    }
    const client = targetClient(data);
    const file = await exportRecoveryManifest(client, "development");
    const approval = {
      environment: "development" as const, writersStopped: true, approveRestore: true,
      allowProductionRestore: false, expectedChecksum: file.checksum,
    };
    await restoreRecoveryManifest(source, client, file, approval, schema, `nulls-${schema}`);
    const result = await inspector.query(
      `select id, request_data::text, response_data::text, response_data is null as sql_null
       from ${quote(schema)}.integration_requests order by id`,
    );
    assert.deepEqual(result.rows, [
      { id: 1, request_data: "null", response_data: null, sql_null: true },
      { id: 2, request_data: "null", response_data: "null", sql_null: false },
    ]);

    const mismatched = nullFixture();
    mismatched.managed_integration_requests[0].response_data = "null";
    await assert.rejects(verifyRecoveryTarget(file, targetClient(mismatched)), /reconciliation/i);
    // Corrupt nullness inside the approved transaction after insertion. Source
    // content reconciliation must reject it and preserve committed JSON null.
    const corruptSource = {
      async query(text: string, values?: unknown[]) {
        const result = await source.query(text, values);
        if (text.startsWith(`insert into ${quote(schema)}."integration_requests"`)) {
          await source.query(`update ${quote(schema)}.integration_requests set response_data = null where id = 2`);
        }
        return result;
      },
    };
    await assert.rejects(
      restoreRecoveryManifest(corruptSource, client, file, approval, schema, `nulls-${schema}`),
      /Recovery restore failed; no rollback receipt issued/,
    );
    assert.equal((await inspector.query(
      `select response_data is null as sql_null from ${quote(schema)}.integration_requests where id = 2`,
    )).rows[0].sql_null, false);
  } finally {
    await inspector.query(`drop schema if exists ${quote(schema)} cascade`).catch(() => undefined);
    source.release(true);
    inspector.release(true);
    await pool.end();
  }
});
}